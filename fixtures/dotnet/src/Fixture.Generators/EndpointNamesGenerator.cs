using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp.Syntax;

namespace Fixture.Generators;

/// <summary>
/// Collects the names given to minimal API endpoints with <c>.WithName("…")</c>
/// into an <c>EndpointNames</c> class of constants.
/// </summary>
[Generator]
public sealed class EndpointNamesGenerator : IIncrementalGenerator
{
    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var names = context.SyntaxProvider
            .CreateSyntaxProvider(
                static (node, _) => node is InvocationExpressionSyntax
                {
                    Expression: MemberAccessExpressionSyntax { Name.Identifier.ValueText: "WithName" },
                    ArgumentList.Arguments.Count: 1,
                },
                static (ctx, _) =>
                    ((InvocationExpressionSyntax)ctx.Node).ArgumentList.Arguments[0].Expression
                        is LiteralExpressionSyntax literal
                        ? literal.Token.ValueText
                        : null)
            .Where(static n => n is not null)
            .Collect();

        context.RegisterSourceOutput(names, static (spc, all) =>
        {
            var source = new StringBuilder()
                .AppendLine("// <auto-generated/>")
                .AppendLine("public static class EndpointNames")
                .AppendLine("{");
            foreach (var name in all.Distinct().OrderBy(n => n))
                source.AppendLine($"    public const string {name} = \"{name}\";");
            source.AppendLine("}");
            spc.AddSource("EndpointNames.g.cs", source.ToString());
        });
    }
}
